package com.klef.soa.docker.service.impl;

import com.klef.soa.docker.dto.TripRequest;
import com.klef.soa.docker.dto.TripResponse;
import com.klef.soa.docker.entity.RideSharingTrip;
import com.klef.soa.docker.repository.RideSharingTripRepository;
import com.klef.soa.docker.service.RideSharingTripService;
import org.springframework.http.HttpStatus;
import org.springframework.stereotype.Service;
import org.springframework.web.server.ResponseStatusException;

import java.util.List;

@Service
public class RideSharingTripServiceImpl implements RideSharingTripService {

    private final RideSharingTripRepository repository;

    public RideSharingTripServiceImpl(RideSharingTripRepository repository) {
        this.repository = repository;
    }

    @Override
    public TripResponse addTrip(TripRequest request) {
        String pickup = request.getPickupLocation().trim();
        String drop = request.getDropLocation().trim();

        if (pickup.equalsIgnoreCase(drop)) {
            throw new ResponseStatusException(HttpStatus.BAD_REQUEST,
                    "Pickup and drop locations must be different");
        }

        RideSharingTrip trip = new RideSharingTrip(pickup, drop, request.getFare(), request.getCompleted());
        return toResponse(repository.save(trip));   // id is generated by the database
    }

    @Override
    public List<TripResponse> getAllTrips() {
        return repository.findAll().stream().map(this::toResponse).toList();
    }

    @Override
    public void deleteTrip(Long id) {
        if (!repository.existsById(id)) {
            throw new ResponseStatusException(HttpStatus.NOT_FOUND, "Trip with id " + id + " not found");
        }
        repository.deleteById(id);
    }

    private TripResponse toResponse(RideSharingTrip t) {
        return new TripResponse(t.getId(), t.getPickupLocation(), t.getDropLocation(),
                t.getFare(), t.getCompleted());
    }
}
